"""Frame-by-frame parity test against gorisanson/pikachu-volleyball physics.js.

This is the audit-4 deliverable: the golden scenario tests previously
locked in our own port as the reference, which couldn't catch drift
from the upstream JS itself. This test runs both engines with a
deterministic Mulberry32 RNG and a scripted input sequence, then
asserts each of the 500 frames is bit-identical on every field that
both engines surface.

The fixture ``backend/tests/fixtures/original_frames.json`` was
generated by the Node harness at ``/tmp/parity-harness/run.mjs``
(checked into ``docs/`` for reproducibility — see commit message of
the audit-4 commit). To regenerate after an upstream change:

    cd /tmp/parity-harness
    node run.mjs > backend/tests/fixtures/original_frames.json

Mulberry32 was chosen as the parity RNG because it's bit-identical
across JS (`Math.imul` semantics) and Python (32-bit int arithmetic),
so the engine-internal stochastic decisions (zero-vx tiebreak at
physics.js:698, computer_boldness at physics.js:213) consume the
same sequence on both sides.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import pytest

from backend.game.engine import PikachuVolleyball, PlayerInput

FIXTURE_PATH = Path(__file__).parent / "fixtures" / "original_frames.json"


# ─── Mulberry32 — bit-exact port of the JS harness's RNG. ─────────────────────


def _imul_u32(a: int, b: int) -> int:
    """JS ``Math.imul`` semantics: lower 32 bits of (a * b) treating both as
    signed int32. Returned as the uint32 bit-pattern (matching JS's
    ``(x | 0) & 0xFFFFFFFF`` behavior)."""
    a_signed = a if a < 0x80000000 else a - 0x100000000
    b_signed = b if b < 0x80000000 else b - 0x100000000
    return (a_signed * b_signed) & 0xFFFFFFFF


def mulberry32(seed: int):
    state = [seed & 0xFFFFFFFF]

    def f() -> float:
        state[0] = (state[0] + 0x6D2B79F5) & 0xFFFFFFFF
        t = state[0]
        a = (t ^ (t >> 15)) & 0xFFFFFFFF
        b = (t | 1) & 0xFFFFFFFF
        t = _imul_u32(a, b)
        a2 = (t ^ (t >> 7)) & 0xFFFFFFFF
        b2 = (t | 61) & 0xFFFFFFFF
        prod2 = _imul_u32(a2, b2)
        t = (t ^ ((t + prod2) & 0xFFFFFFFF)) & 0xFFFFFFFF
        return ((t ^ (t >> 14)) & 0xFFFFFFFF) / 4294967296

    return f


def js_rand_factory(seed: int):
    """Returns a callable matching original ``rand()`` (rand.js:24-29):
    ``Math.floor(32768 * customRng())`` → int in [0, 32767]."""
    rng = mulberry32(seed)
    return lambda: math.floor(32768 * rng())


# ─── Input script — must match ``inputAtFrame`` in /tmp/parity-harness/run.mjs.


def _input_at_frame(i: int) -> tuple[PlayerInput, PlayerInput]:
    p1_x, p1_y, p1_pwr = 0, 0, False
    if i % 17 == 0:
        p1_y = -1
    if i % 23 == 0:
        p1_x = 1
    if i % 29 == 0:
        p1_x = -1
    if i % 41 == 0:
        p1_pwr = True
    if i % 67 == 0:
        p1_x = 1
        p1_pwr = True

    p2_x, p2_y, p2_pwr = 0, 0, False
    if i % 19 == 0:
        p2_y = -1
    if i % 31 == 0:
        p2_x = -1
    if i % 37 == 0:
        p2_x = 1
    if i % 43 == 0:
        p2_pwr = True
    if i % 71 == 0:
        p2_x = -1
        p2_pwr = True

    return (
        PlayerInput(x_dir=p1_x, y_dir=p1_y, power_hit=p1_pwr),
        PlayerInput(x_dir=p2_x, y_dir=p2_y, power_hit=p2_pwr),
    )


# ─── Parity engine subclass — overrides _rand to use Mulberry32. ──────────────


class _ParityEngine(PikachuVolleyball):
    """PikachuVolleyball reduced to pure-physics parity for the JS dump.

    The harness compares against ``PikaPhysics.runEngineForNextFrame``
    only — that's the original ``physicsEngine`` (FUN_00403dd0), which
    deliberately does not own scoring or round reset (those live in
    ``pikavolley.js``'s controller). Our engine layers _handle_scoring
    on top inside ``step()``; for pure-physics parity we no-op it so
    the grounded-ball bounce sequence keeps playing out exactly as the
    JS dump (where the controller is also absent).

    Rally-timeout safety valve is also disabled — extension we added
    for headless RL play, not in upstream physics.

    RNG is replaced by Mulberry32 so the engine consumes the same
    rand sequence as the JS harness.
    """

    def __init__(self, seed: int) -> None:
        self._rand_fn = js_rand_factory(seed)
        super().__init__()
        # Pull rally-timeout out of the way so it can't preempt parity.
        self.RALLY_MAX_FRAMES = 10**9

    def _rand(self) -> int:
        return self._rand_fn()

    def _handle_scoring(self, state) -> None:  # type: ignore[override]
        # Pure physics parity — the upstream physicsEngine doesn't own
        # scoring. Leaving the grounded ball mid-bounce so JS-side and
        # Python-side both keep applying gravity / world collisions.
        pass

    def _handle_rally_timeout(self, state) -> None:  # type: ignore[override]
        pass

    def step(self, p1_input: PlayerInput, p2_input: PlayerInput):  # type: ignore[override]
        # Bypass the production step() entirely. The production path
        # short-circuits on ball ground-touch to invoke _handle_scoring
        # before the player updates run; the upstream physicsEngine
        # (FUN_00403dd0) does NOT — it returns isBallTouchingGround as
        # a flag and keeps running the player + collision passes. Mirror
        # that ordering here for a frame-accurate physics-only compare.
        state = self._state
        state.frame += 1
        self._update_ball_and_world(state.ball)
        # Original calls calculateExpectedLandingPointXFor at the head
        # of each player loop iteration (physics.js:323).
        self._calculate_expected_landing_point_x(state.ball)
        self._update_player(
            state.player1, p1_input, is_player2=False,
            ball=state.ball, other=state.player2,
        )
        self._calculate_expected_landing_point_x(state.ball)
        self._update_player(
            state.player2, p2_input, is_player2=True,
            ball=state.ball, other=state.player1,
        )
        self._check_ball_player_collision(state.ball, state.player1, p1_input)
        self._check_ball_player_collision(state.ball, state.player2, p2_input)
        return state


# ─── Parity test ──────────────────────────────────────────────────────────────


def _serialize_for_parity(state) -> dict:
    """Subset of GameState fields the JS harness surfaces."""
    return {
        "p1": {
            "x": state.player1.x,
            "y": state.player1.y,
            "vy": state.player1.vy,
            "state": state.player1.state,
            "frameNumber": state.player1.frame_number,
            "lyingDownDurationLeft": state.player1.lying_down_duration_left,
            "isCollisionWithBallHappened": state.player1.is_collision_with_ball_happened,
        },
        "p2": {
            "x": state.player2.x,
            "y": state.player2.y,
            "vy": state.player2.vy,
            "state": state.player2.state,
            "frameNumber": state.player2.frame_number,
            "lyingDownDurationLeft": state.player2.lying_down_duration_left,
            "isCollisionWithBallHappened": state.player2.is_collision_with_ball_happened,
        },
        "ball": {
            "x": state.ball.x,
            "y": state.ball.y,
            "vx": state.ball.vx,
            "vy": state.ball.vy,
            "rotation": state.ball.rotation,
            "fineRotation": state.ball.fine_rotation,
            "isPowerHit": state.ball.is_power_hit,
            "expectedLandingPointX": state.ball.expected_landing_point_x,
        },
    }


@pytest.mark.parametrize("frame_field,subfield", [
    ("p1", "x"),
    ("p1", "y"),
    ("p1", "vy"),
    ("p1", "state"),
    ("p1", "frameNumber"),
    ("p1", "lyingDownDurationLeft"),
    ("p1", "isCollisionWithBallHappened"),
    ("p2", "x"),
    ("p2", "y"),
    ("p2", "vy"),
    ("p2", "state"),
    ("p2", "frameNumber"),
    ("p2", "lyingDownDurationLeft"),
    ("p2", "isCollisionWithBallHappened"),
    ("ball", "x"),
    ("ball", "y"),
    ("ball", "vx"),
    ("ball", "vy"),
    ("ball", "rotation"),
    ("ball", "fineRotation"),
    ("ball", "isPowerHit"),
    ("ball", "expectedLandingPointX"),
])
def test_parity_500_frames(frame_field: str, subfield: str) -> None:
    """For each (entity, field) tuple, every frame must match the JS dump.

    Parametrized so a divergence on a single field is reported with the
    field name + first-divergent-frame, not buried in a noisy mega-diff.
    """
    if not FIXTURE_PATH.exists():
        pytest.skip(
            f"fixture missing: {FIXTURE_PATH} — regenerate via "
            "/tmp/parity-harness/run.mjs"
        )
    fixture = json.loads(FIXTURE_PATH.read_text())
    seed = int(fixture["seed"])
    expected_frames = fixture["frames"]

    game = _ParityEngine(seed=seed)
    actual_frames = []
    for i in range(len(expected_frames)):
        p1_inp, p2_inp = _input_at_frame(i)
        game.step(p1_inp, p2_inp)
        actual_frames.append(_serialize_for_parity(game._state))

    diffs: list[tuple[int, object, object]] = []
    for i, (exp, act) in enumerate(zip(expected_frames, actual_frames)):
        e = exp[frame_field][subfield]
        a = act[frame_field][subfield]
        if e != a:
            diffs.append((i, e, a))
            if len(diffs) >= 5:
                break

    if diffs:
        msg = f"{frame_field}.{subfield} diverged from upstream JS:\n"
        for f, e, a in diffs:
            msg += f"  frame {f}: expected={e!r} actual={a!r}\n"
        pytest.fail(msg)
